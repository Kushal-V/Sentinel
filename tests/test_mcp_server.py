# Fixtures
# ---------------------------------------------------------------------------


@pytest.fixture
def temp_workspaces_root(tmp_path, monkeypatch):
    """Redirect WORKSPACES_DIR to a temp directory across all import sites.

    Returns the (now-redirected) workspaces root Path. Tests can create
    workspace subdirectories under this root and they will be found by
    ``_build_server``.
    """
    ws_root = tmp_path / "workspaces"
    ws_root.mkdir(parents=True)

    # Patch the constant at every import site that has already cached it.
    monkeypatch.setattr("src.core.config.WORKSPACES_DIR", ws_root)
    monkeypatch.setattr("src.core.state_manager.WORKSPACES_DIR", ws_root)
    monkeypatch.setattr("src.mcp_server.server.WORKSPACES_DIR", ws_root)

    return ws_root


@pytest.fixture
def populated_workspace(temp_workspaces_root) -> str:
    """Create a minimal workspace on disk and return its name.

    Writes a small inventory CSV. The transaction log and trust scores
    are auto-generated by :class:`FactoryDataManager` on first access,
    so we don't need to seed them here.
    """
    ws_name = "test_ws"
    ws_dir: Path = temp_workspaces_root / ws_name
    ws_dir.mkdir()

    inventory = pd.DataFrame(
        [
            {
                "item_id": "ITEM-A",
                "current_stock": 100,
                "max_capacity": 500,
                "unit_cost_usd": 1.0,
            },
            {
                "item_id": "ITEM-B",
                "current_stock": 50,
                "max_capacity": 200,
                "unit_cost_usd": 2.5,
            },
        ]
    )
    inventory.to_csv(ws_dir / "inventory.csv", index=False)
    return ws_name


@pytest.fixture(autouse=True)
def reset_tool_data_manager():
    """Clear the tool registry's data manager singleton between tests.

    ``set_data_manager`` is a process-wide mutation; without resetting
    we'd leak state into subsequent tests (e.g. one test's
    FactoryDataManager pointing at a tmp dir that has been removed).
    """
    yield
    from src.tools import tool_registry

    tool_registry._data_manager = None


