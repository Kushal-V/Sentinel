"""tests/test_mcp_server.py
=========================
Unit tests for the Sentinel MCP server wrapper.

Scope
-----
The MCP server uses asyncio + stdio. Full integration testing requires
spinning up a stdio loop and a paired client, which is heavy and brittle
in CI. These tests focus on what can be verified deterministically and
without network/stdio:

1. ``_build_server`` returns a configured ``mcp.server.Server`` for a
   valid workspace.
2. ``_build_server`` raises ``FileNotFoundError`` for a missing workspace.
3. ``_build_server`` rejects path-traversal workspace names (delegated
   to :class:`FactoryDataManager`'s constructor validation).
4. The data manager is registered as the tool-registry singleton after
   ``_build_server`` runs (verifies the wrapper is wired up correctly).

End-to-end MCP transport integration tests are deferred to a Phase 5+
manual run with Claude Desktop.

Workspace patching note
-----------------------
``WORKSPACES_DIR`` is a module-level constant referenced from THREE
places: :mod:`src.core.config`, :mod:`src.core.state_manager` (which
imports it directly), and :mod:`src.mcp_server.server` (which also
imports it directly). Each direct import binds its own name, so we
monkeypatch all three to point the test at a temporary directory.
"""

from __future__ import annotations

import sys
from pathlib import Path

# Ensure the project root is on sys.path so ``src`` resolves when pytest
# is invoked from any working directory. Mirrors the pattern already used
# in tests/test_edge_cases.py.
_PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(_PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(_PROJECT_ROOT))

import pandas as pd
import pytest


