def test_build_server_returns_configured_server(populated_workspace):
    """Happy path: an existing workspace yields a usable Server object."""
    from mcp.server import Server as MCPServer

    from src.mcp_server.server import _build_server

    server = _build_server(populated_workspace)

    assert server is not None
    assert isinstance(server, MCPServer)
    # The Server is named 'sentinel-mcp' so MCP clients can identify it.
    assert server.name == "sentinel-mcp"


def test_build_server_unknown_workspace_raises(temp_workspaces_root):
    """A non-existent workspace name produces a FileNotFoundError."""
    from src.mcp_server.server import _build_server

    with pytest.raises(FileNotFoundError) as excinfo:
        _build_server("does_not_exist")

    assert "Workspace not found" in str(excinfo.value)


def test_build_server_rejects_path_traversal(temp_workspaces_root):
    """Path-traversal workspace names are rejected by the data manager.

    The FactoryDataManager constructor raises ValueError on any name
    containing ``..``, ``/``, or ``\\``. Verify the MCP server does not
    bypass that check.
    """
    from src.mcp_server.server import _build_server

    # Create a directory that LOOKS like the resolved target so the
    # FileNotFoundError doesn't fire first — we want to confirm the
    # ValueError from FactoryDataManager wins. With ".." in the name,
    # WORKSPACES_DIR / ".." resolves to tmp_path itself, which exists.
    with pytest.raises(ValueError) as excinfo:
        _build_server("..")
    assert "Invalid workspace name" in str(excinfo.value)


def test_build_server_registers_data_manager_singleton(populated_workspace):
    """After _build_server, the tool registry's singleton points at the new manager."""
    from src.mcp_server.server import _build_server
    from src.tools.tool_registry import get_data_manager

    server = _build_server(populated_workspace)
    assert server is not None

    dm = get_data_manager()
    assert dm.workspace == populated_workspace


def test_build_server_inventory_loads(populated_workspace):
    """Confirm the seeded inventory is reachable via the data manager.

    This catches the failure mode where _build_server points at the
    wrong directory (e.g. ``WORKSPACES_DIR`` not patched at every site)
    and silently auto-generates mock data instead of loading the
    workspace we created.
    """
    from src.mcp_server.server import _build_server
    from src.tools.tool_registry import get_data_manager

    _build_server(populated_workspace)
    df = get_data_manager().get_inventory()

    assert "item_id" in df.columns
    assert set(df["item_id"]) == {"ITEM-A", "ITEM-B"}


