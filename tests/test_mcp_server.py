def test_package_exports():
    """The package re-exports the public surface."""
    import src.mcp_server as pkg

    assert hasattr(pkg, "run_server")
    assert hasattr(pkg, "_build_server")
    assert "run_server" in pkg.__all__
    assert "_build_server" in pkg.__all__


